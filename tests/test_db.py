class _MockPgCursor:
    """Adapter translating %s PostgreSQL queries onto an isolated SQLite DB."""

    def __init__(self, inner: sqlite3.Cursor, queries: list[str]) -> None:
        self._inner = inner
        self._queries = queries

    def _adapt(self, sql: str) -> str:
        self._queries.append(" ".join(sql.split()))
        return (
            sql.replace("INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", "INTEGER PRIMARY KEY AUTOINCREMENT")
            .replace("DOUBLE PRECISION", "REAL")
            .replace("BOOLEAN", "INTEGER")
            .replace("TIMESTAMPTZ NOT NULL DEFAULT NOW()", "TEXT NOT NULL DEFAULT (datetime('now'))")
            .replace("%s", "?")
        )

    def execute(self, sql: str, params=()):
        self._inner.execute(self._adapt(sql), params)
        return self

    def executemany(self, sql: str, seq):
        self._inner.executemany(self._adapt(sql), seq)
        return self

    def fetchone(self):
        row = self._inner.fetchone()
        return dict(row) if row is not None else None

    def fetchall(self):
        return [dict(r) for r in self._inner.fetchall()]

    @property
    def rowcount(self) -> int:
        return self._inner.rowcount

    def close(self) -> None:
        self._inner.close()


class _MockPgConnection:
    """Fake psycopg v3 connection tracking calls, transactions, and queries."""

    def __init__(self, sqlite_path: str, queries: list[str], events: list[str]) -> None:
        self._conn = sqlite3.connect(sqlite_path)
        self._conn.row_factory = sqlite3.Row
        self._conn.execute("PRAGMA foreign_keys = ON;")
        self._queries = queries
        self._events = events

    def cursor(self) -> _MockPgCursor:
        return _MockPgCursor(self._conn.cursor(), self._queries)

    def execute(self, sql: str, params=()) -> _MockPgCursor:
        return self.cursor().execute(sql, params)

    def commit(self) -> None:
        self._events.append("commit")
        self._conn.commit()

    def rollback(self) -> None:
        self._events.append("rollback")
        self._conn.rollback()

    def close(self) -> None:
        self._events.append("close")
        self._conn.close()


def test_database_url_normalization_and_fallback(monkeypatch, tmp_path):
    monkeypatch.delenv("DATABASE_URL", raising=False)
    monkeypatch.setenv("EARTHQUICK_DB_PATH", str(tmp_path / "local.db"))
    assert db.get_database_url() is None
    assert db._resolve_target() == ("sqlite", str(tmp_path / "local.db"))

    monkeypatch.setenv("DATABASE_URL", "postgres://user:pass@dpg-host:5432/earthquick")
    assert db.get_database_url() == "postgresql://user:pass@dpg-host:5432/earthquick"
    assert db._resolve_target() == ("postgres", "postgresql://user:pass@dpg-host:5432/earthquick")


def test_postgres_psycopg_crud_cascade_and_rollback(monkeypatch, tmp_path):
    backing_file = str(tmp_path / "mock_pg.db")
    queries: list[str] = []
    events: list[str] = []
    connect_calls: list[tuple[str, object]] = []

    def fake_connect(conninfo: str, row_factory=None):
        connect_calls.append((conninfo, row_factory))
        return _MockPgConnection(backing_file, queries, events)

    db._INITIALIZED_TARGETS.clear()
    monkeypatch.setenv("DATABASE_URL", "postgres://u:p@render-pg.internal:5432/earthquick_db")
    monkeypatch.setattr(db.psycopg, "connect", fake_connect)

    db.init_db()
    assert any("GENERATED BY DEFAULT AS IDENTITY" in q for q in queries)
    assert connect_calls[0][0] == "postgresql://u:p@render-pg.internal:5432/earthquick_db"
    assert connect_calls[0][1] is db.dict_row

    saved = db.save_building(
        name="PG Shear Tower",
        building_type="Steel Frame",
        damping_ratio=0.05,
        masses=[150.0, 130.0, 110.0],
        stiffnesses=[32000.0, 28000.0, 24000.0],
    )
    assert saved["id"] == 1
    assert saved["floors"] == 3
    assert saved["masses"] == [150.0, 130.0, 110.0]
    assert any("RETURNING *" in q and "%s" in q for q in queries)

    M = assemble_mass_matrix(saved["masses"])
    K = assemble_stiffness_matrix(saved["stiffnesses"])
    mat = analyze_matrices(M, K)
    mod_raw = solve_modal_analysis(M, K)
    mod_payload = {
        "eigenvalues": mod_raw["eigenvalues"].tolist(),
        "omega": mod_raw["omega"].tolist(),
        "frequencies_hz": mod_raw["frequencies_hz"].tolist(),
        "periods_s": mod_raw["periods_s"].tolist(),
        "phi_normalized": mod_raw["phi_normalized"].tolist(),
        "participation_factors": mod_raw["participation_factors"].tolist(),
        "mass_ratio_pct": mod_raw["mass_ratio_pct"].tolist(),
        "eigen_residual": float(mod_raw["eigen_residual"]),
    }
    saved_modal = db.save_modal_analysis(saved["id"], mat, mod_payload)
    assert saved_modal["is_spd"] is True

    t, ag = generate_ground_motion("Broadband Seismic Pulse", duration_s=5.0, dt=0.01, pga_g=0.25)
    eq_raw = simulate_earthquake(M, K, 0.05, t, ag)
    eq_payload = {
        "pga_g": eq_raw["pga_g"],
        "peak_roof_disp_mm": eq_raw["peak_roof_disp_mm"],
        "max_interstory_drift_mm": eq_raw["max_interstory_drift_mm"],
        "critical_story": eq_raw["critical_story"],
        "peak_base_shear_kn": eq_raw["peak_base_shear_kn"],
        "peak_floor_disp_mm": eq_raw["peak_floor_disp_mm"].tolist(),
        "peak_story_drift_mm": eq_raw["peak_story_drift_mm"].tolist(),
        "risk_level": eq_raw["risk_level"],
    }
    saved_quake = db.save_earthquake_run(
        saved["id"], saved_modal["id"], "preset", "Broadband Seismic Pulse", 5.0, eq_payload
    )

    detail = db.get_run_detail("quake", saved_quake["id"])
    assert detail is not None
    assert len(detail["modal"]["eigenvalues"]) == 3
    assert detail["earthquake"]["risk_level"] in {"Low", "Moderate", "High", "Severe"}
    assert len(db.list_history()) == 1

    # Timestamp helper converts Postgres datetime objects cleanly for JSON serialization
    assert db._iso_ts(datetime(2026, 1, 1, tzinfo=timezone.utc)).startswith("2026-01-01")

    # Transaction failure rolls back cleanly without leaking connections
    events.clear()
    with pytest.raises(RuntimeError):
        with db._tx() as (conn, _):
            conn.execute("INSERT INTO buildings (name, building_type, floors, damping_ratio) VALUES (%s, %s, %s, %s)", ("Tmp", "custom", 3, 0.05))
            raise RuntimeError("abort tx")
    assert events == ["rollback", "close"]
    assert len(db.list_buildings()) == 1

    # Persist resonance check and storey stiffness comparison linked to the building
    res_payload = {
        "freq_min_hz": 1.0,
        "freq_max_hz": 3.5,
        "has_resonance_risk": True,
        "at_risk_modes": [{"mode": 1, "frequency_hz": 1.4, "period_s": 0.71, "at_risk": True}],
        "modes": [{"mode": 1, "frequency_hz": 1.4, "period_s": 0.71, "at_risk": True}],
        "summary": "Potential resonance risk detected within 1.00–3.50 Hz: Mode 1 (1.400 Hz).",
    }
    saved_res = db.save_resonance_check(saved["id"], saved_modal["id"], res_payload)
    assert saved_res["has_resonance_risk"] is True

    cmp_payload = {
        "story_index": 1,
        "orig_stiffness_kn_m": 32000.0,
        "mod_stiffness_kn_m": 40000.0,
        "pct_change": 25.0,
        "modes": [{"mode": 1, "orig_freq_hz": 1.4, "mod_freq_hz": 1.5, "change_pct": 7.14}],
        "explanation": "Increasing Storey 1 stiffness raises f1.",
    }
    saved_cmp = db.save_stiffness_comparison(saved["id"], cmp_payload)
    assert saved_cmp["story_index"] == 1

    history = db.list_history()
    assert {item["run_type"] for item in history} == {"quake", "resonance", "stiffness"}
    assert db.get_run_detail("resonance", saved_res["id"])["resonance"]["has_resonance_risk"] is True
    assert db.get_run_detail("stiffness", saved_cmp["id"])["comparison"]["pct_change"] == pytest.approx(25.0)

    # Foreign-key CASCADE deletes child modal, quake, resonance, and stiffness runs
    assert db.delete_building(saved["id"]) is True
    assert db.get_run_detail("quake", saved_quake["id"]) is None
    assert db.get_run_detail("resonance", saved_res["id"]) is None
    assert db.get_run_detail("stiffness", saved_cmp["id"]) is None
    assert db.list_history() == []


def test_sqlite_local_fallback_crud_and_validation(monkeypatch, tmp_path):
    monkeypatch.delenv("DATABASE_URL", raising=False)
    db_file = tmp_path / "fallback.db"
    db.init_db(db_file)

    saved = db.save_building(
        name="3-Story Office",
        building_type="Concrete Frame",
        damping_ratio=0.05,
        masses=[150.0, 130.0, 110.0],
        stiffnesses=[32000.0, 28000.0, 24000.0],
        db_path=db_file,
    )
    assert saved["floors"] == 3
    assert db.get_building(saved["id"], db_path=db_file)["name"] == "3-Story Office"
    assert db.delete_building(saved["id"], db_path=db_file) is True
    assert db.list_buildings(db_path=db_file) == []

    with pytest.raises(ValueError):
        db.save_building("Two Floors", "custom", 0.05, [100.0, 100.0], [20000.0, 20000.0], db_path=db_file)
    with pytest.raises(ValueError):
        db.save_building("Six Floors", "custom", 0.05, [100.0] * 6, [20000.0] * 6, db_path=db_file)
    with pytest.raises(ValueError):
        db.save_building("Bad Stiffness", "custom", 0.05, [100.0, 100.0, 100.0], [20000.0, -5.0, 20000.0], db_path=db_file)
